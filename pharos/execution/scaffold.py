def write_main_codex_config(project: str, model: str,
                            into: Optional[Path] = None) -> None:
    """Write a main-role ``.codex/config.toml`` — for the project dir itself
    (the resident main agent) or, via ``into``, for another cwd that runs with
    the main agent's wiring (the ``chat/`` discussion instance). The MCP stays
    pinned to the PROJECT dir either way."""
    pdir = L.project_dir(project)
    atomic_write((into or pdir) / ".codex" / "config.toml", _MAIN_CODEX_CONFIG.format(
        model=_toml_str(model),
        python=_toml_str(sys.executable),
        project_dir=_toml_str(str(pdir)),
        verify_timeout=_toml_str(_verify_timeout()),
    ))


def do_new(project: str, roles: str = "xhigh:3,max:4",
           model: Optional[str] = None, port: Optional[int] = None) -> Dict:
    """Scaffold a project dir + one worker home per role. Refuses to clobber an
    existing project dir (no silent overwrite of a live fact graph). The verify
    port is ``port`` when given (refused if a sibling claims it or the host holds
    it), else the lowest free one at/above the base. Returns
    ``{"project_dir", "workers", "verify_port"}``."""
    pdir = L.project_dir(project)
    if pdir.exists():
        raise SystemExit(f"project already exists: {pdir} (pick another name or remove it)")
    role_pairs = L.parse_roles(roles)
    model = model or _default_model()
    if port is not None:
        problem = verify_port_problem(port)
        if problem:
            raise SystemExit(problem)
        verify_port = port
    else:
        verify_port = allocate_verify_port()

    L.workers_dir(project).mkdir(parents=True, exist_ok=True)
    (pdir / "global_memory").mkdir(exist_ok=True)
    (pdir / "fact_graph").mkdir(exist_ok=True)
    ensure_verifier_home(project)
    L.materials_dir(project).mkdir(exist_ok=True)
    L.subagents_dir(project).mkdir(exist_ok=True)
    # Reports and chat sessions have separate homes; checkpoints use the main session.
    (L.human_report_dir(project) / "md").mkdir(parents=True, exist_ok=True)
    (L.human_report_dir(project) / "pdf").mkdir(parents=True, exist_ok=True)
    L.checkpoints_dir(project).mkdir(exist_ok=True)
    # ROUTES.md: the live route board, seeded once, never overwritten
    if not L.routes_md(project).exists():
        atomic_write(L.routes_md(project), _ROUTES_SEED)
    # Literature files are shared by workers and helpers.
    (L.literature_dir(project) / "papers").mkdir(parents=True, exist_ok=True)
    (L.literature_dir(project) / "notes").mkdir(exist_ok=True)
    # Preserve existing operator instructions when provisioning templates.
    L.expert_guidance_dir(project).mkdir(exist_ok=True)
    for name, seed in (("INSTRUCTIONS.md", _INSTRUCTIONS_SEED),
                       ("GUIDANCE.md", _GUIDANCE_SEED)):
        seed_path = L.expert_guidance_dir(project) / name
        if not seed_path.exists():
            atomic_write(seed_path, seed)
    ensure_style_dir(project)
    L.computation_dir(project).mkdir(exist_ok=True)

    # Worker configs resolve the verifier URL from this metadata.
    meta = {"name": project, "model": model, "roles": roles,
            "workers": [w for w, _ in role_pairs], "verify_port": verify_port,
            "created_at": int(time.time())}
    atomic_write(pdir / "project.json", json.dumps(meta, ensure_ascii=False, indent=2))
    ensure_chat_home(project)          # needs project.json (the model it mirrors)
    ensure_reporter_home(project)

    # The project uses the main-agent contract and skills, with its own session store.
    symlink(L.main_md(), pdir / "AGENTS.md")
    symlink(L.repo_root() / "OPERATOR.md", pdir / "OPERATOR.md")
    (pdir / ".agents").mkdir(exist_ok=True)
    symlink(L.main_skills_dir(), pdir / ".agents" / "skills")
    write_main_codex_config(project, model)
    codex.provision_codex_home(L.main_codex_home(project))

    created: List[str] = []
    for worker, base in role_pairs:
        wl = L.WorkerLayout(L.worker_dir(project, worker))
        wl.local_memory.mkdir(parents=True, exist_ok=True)
        wl.logs.mkdir(exist_ok=True)

        # static contract + skills (symlinks stay in sync with the repo)
        symlink(L.worker_md(), wl.dir / "AGENTS.md")
        (wl.dir / ".agents").mkdir(exist_ok=True)
        symlink(L.worker_skills_dir(), wl.dir / ".agents" / "skills")

        # codex MCP wiring (role=worker) + this worker's own conversation store
        write_codex_config(wl)
        codex.provision_codex_home(wl.codex_home)
        atomic_write(wl.task, _TASK_PLACEHOLDER)
        atomic_write(wl.role,
                     f"MODEL={model}\nREASONING_EFFORT={base}\nROLE={base}\nPHAROS_AUTHOR={worker}\n")
        atomic_write(wl.status,
                     json.dumps({"worker": worker, "state": "created", "round": 0}, indent=2))
        created.append(worker)

    return {"project_dir": str(pdir), "workers": created, "verify_port": verify_port}


