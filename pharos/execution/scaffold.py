def _project_model(project: str) -> str:
    try:
        return json.loads((L.project_dir(project) / "project.json")
                          .read_text(encoding="utf-8"))["model"]
    except (OSError, json.JSONDecodeError, KeyError):
        return codex.model()


def ensure_side_home(project: str, home: Path, contract: Path, skills: Path,
                     author: str, role: str = "reader") -> Path:
    """Provision one side-actor home (idempotent): contract as AGENTS.md, its
    skills, a role-pinned MCP config, its own session store, a logs dir."""
    if not L.project_dir(project).is_dir():
        raise SystemExit(f"no such project: {project}")
    (home / ".agents").mkdir(parents=True, exist_ok=True)
    symlink(contract, home / "AGENTS.md")
    symlink(skills, home / ".agents" / "skills")
    atomic_write(home / ".codex" / "config.toml", _SIDE_CODEX_CONFIG.format(
        model=_toml_str(_project_model(project)), python=_toml_str(sys.executable),
        role=_toml_str(role), author=_toml_str(author),
        project_dir=_toml_str(str(L.project_dir(project)))))
    codex.provision_codex_home(home / ".codex-home")
    (home / "logs").mkdir(exist_ok=True)
    return home


def ensure_reporter_home(project: str) -> Path:
    return ensure_side_home(project, L.reporter_dir(project), L.contract("reporter"),
                            L.skills("reporter"), author="reporter")


_SECTION_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")


def ensure_section_home(project: str, name: str) -> Path:
    """A section writer's home under paper/src/sections/, plus that section's
    own stateful verifier home inside it."""
    if not _SECTION_RE.match(name):
        raise SystemExit(f"bad section name {name!r} (letters, digits, . _ - only)")
    ensure_paper_workspace(project)
    home = ensure_side_home(project, L.section_dir(project, name),
                            L.contract("section_writer"), L.skills("section"),
                            author=f"section:{name}")
    ensure_side_home(project, L.section_verifier_dir(project, name),
                     L.contract("paper_verifier"), L.skills("paper-verify"),
                     author=f"paper_verifier:{name}")
    return home


def ensure_style_dir(project: str) -> Path:
    """``<project>/style/`` — the paper's style layer (the `paper-style`
    skill): README.md (how to customize, copied once from the default package),
    ``default`` -> the repo's default style package, and beside them whatever
    the operator adds (STYLE.md, TEMPLATE.tex, exemplar/). Idempotent; never
    overwrites what is there."""
    sdir = L.style_dir(project)
    sdir.mkdir(parents=True, exist_ok=True)
    default = L.default_style_dir()
    readme = default / "README.md"
    if readme.is_file() and not (sdir / "README.md").exists():
        shutil.copy(readme, sdir / "README.md")
    symlink(default, sdir / "default")
    return sdir


def ensure_paper_workspace(project: str) -> Path:
    """Provision paper sections, the template copy, style files, and verifier home.

    Existing template and style files are preserved.
    """
    pdir = L.paper_dir(project)
    ensure_style_dir(project)
    L.sections_dir(project).mkdir(parents=True, exist_ok=True)
    local, shared = L.paper_src_dir(project) / "template.tex", L.paper_template(project)
    if not local.exists() and shared.is_file():
        shutil.copy(shared, local)
    ensure_side_home(project, L.paper_verifier_dir(project), L.contract("paper_verifier"),
                     L.skills("paper-verify"), author="paper_verifier:global")
    return pdir


def ensure_chat_home(project: str) -> Path:
    """Provision a chat home with main-role tools and a separate session store."""
    pdir = L.project_dir(project)
    if not pdir.is_dir():
        raise SystemExit(f"no such project: {project}")
    cdir = L.chat_dir(project)
    cdir.mkdir(exist_ok=True)
    symlink(L.repo_root() / "agents" / "contracts" / "chat.md", cdir / "AGENTS.md")
    write_main_codex_config(project, _project_model(project), into=cdir)
    codex.provision_codex_home(cdir / ".codex-home")
    return cdir


def ensure_verifier_home(project: str) -> Path:
    """Provision the verifier's contract, skills, sessions, and run logs in its home."""
    home = L.verifier_dir(project)
    home.mkdir(parents=True, exist_ok=True)
    symlink(L.verifier_md(), home / "AGENTS.md")
    (home / ".agents").mkdir(exist_ok=True)
    symlink(L.verify_skills_dir(), home / ".agents" / "skills")
    L.verifier_runs_dir(project).mkdir(exist_ok=True)
    codex.provision_codex_home(L.verifier_codex_home(project))
    return home


_SUB_RE = re.compile(r"^sub[1-9]\d*$")


def ensure_subagent(project: str, name: Optional[str] = None) -> Path:
    """Provision (or reuse) one subagent dir under ``<project>/subagents/``.

    ``name=None`` allocates the next free ``subN`` atomically (mkdir is the
    lock). An explicit ``name`` must match ``subN`` and is created/reused
    idempotently — reuse lets the main agent continue an existing helper.
    Every home gets its own ``.codex-home`` (sessions separate per helper)
    and a ``logs/`` dir for the launcher's stdout captures."""
    if not L.project_dir(project).is_dir():
        raise SystemExit(f"unknown project: {project}")
    root = L.subagents_dir(project)
    root.mkdir(parents=True, exist_ok=True)
    if name is not None:
        if not _SUB_RE.match(name):
            raise SystemExit(f"subagent name must look like sub1/sub2/…, got {name!r}")
        sdir = root / name
        sdir.mkdir(exist_ok=True)
    else:
        n = 1
        while True:
            sdir = root / f"sub{n}"
            try:
                sdir.mkdir()
                break
            except FileExistsError:
                n += 1
    (sdir / "logs").mkdir(exist_ok=True)
    # helpers run the main agent's errands (literature, digests): the read-only
    # reader role gives them theorem search and the truth stores, no writes
    atomic_write(sdir / ".codex" / "config.toml", _SIDE_CODEX_CONFIG.format(
        model=_toml_str(_project_model(project)), python=_toml_str(sys.executable),
        role=_toml_str("reader"), author=_toml_str(sdir.name),
        project_dir=_toml_str(str(L.project_dir(project)))))
    codex.provision_codex_home(sdir / ".codex-home")
    return sdir


def spawn_loop(wdir: Path) -> int:
    """Launch ``python -m pharos.execution <wdir>`` detached in its own process
    group (``start_new_session=True``) so ``pharos stop --force`` can ``killpg``
    the loop *and* its in-flight codex child. Returns the child pid."""
    wl = L.WorkerLayout(wdir)
    wl.logs.mkdir(parents=True, exist_ok=True)
    logf = open(wl.logs / "loop.log", "a", encoding="utf-8")
    try:
        proc = subprocess.Popen(
            [sys.executable, "-m", "pharos.execution", str(wdir)],
            stdout=logf, stderr=subprocess.STDOUT, stdin=subprocess.DEVNULL,
            start_new_session=True, env=L.child_env(),
        )
    finally:
        logf.close()
    return proc.pid
