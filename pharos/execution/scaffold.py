def _verify_port_base() -> int:
    """The first port tried when allocating a project's verify port."""
    try:
        return int(os.environ.get("VERIFY_PORT", "") or L.DEFAULT_VERIFY_PORT_BASE)
    except ValueError:
        return L.DEFAULT_VERIFY_PORT_BASE


def _used_verify_ports() -> set:
    """Every ``verify_port`` already claimed by a sibling project.json."""
    used = set()
    root = L.agents_root()
    if root.is_dir():
        for meta in root.glob("*/project.json"):
            try:
                port = json.loads(meta.read_text(encoding="utf-8")).get("verify_port")
            except (json.JSONDecodeError, OSError):
                continue
            if isinstance(port, int):
                used.add(port)
    return used


def port_is_free(port: int, host: str = "127.0.0.1") -> bool:
    """Probe whether ``host:port`` can be bound, releasing the socket immediately."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        try:
            s.bind((host, port))
        except OSError:
            return False
    return True


def verify_port_problem(port: int, project: Optional[str] = None) -> Optional[str]:
    """Why ``port`` cannot be this project's verify port — ``None`` when it can.
    Two reasons: a sibling project of this deployment already claims it in its
    project.json, or some process on the host holds it (typically another Pharos
    deployment allocating from the same base)."""
    if not (1024 <= port <= 65535):
        return f"port {port} is outside 1024–65535"
    for meta in (L.agents_root().glob("*/project.json") if L.agents_root().is_dir() else ()):
        if project and meta.parent.name == project:
            continue
        try:
            if json.loads(meta.read_text(encoding="utf-8")).get("verify_port") == port:
                return f"port {port} is already project {meta.parent.name!r}'s verify port"
        except (json.JSONDecodeError, OSError):
            continue
    if not port_is_free(port):
        return (f"port {port} is held by another process on this host — a foreign "
                f"deployment allocating from the same base? (give each deployment its "
                f"own VERIFY_PORT in config/pharos.env)")
    return None


def allocate_verify_port() -> int:
    """Find the lowest free port from the base, excluding sibling project claims."""
    used = _used_verify_ports()
    base = _verify_port_base()
    for port in range(base, base + 1000):
        if port in used or not port_is_free(port):
            continue
        return port
    raise SystemExit(f"no free verify port in {base}–{base + 999}; set VERIFY_PORT to another base")


def set_verify_port(project: str, port: int) -> Dict:
    """Move a project to ``port``: rewrite ``verify_port`` in its project.json.
    The workers' gateway configs pin the verify URL, but ``write_codex_config``
    regenerates them from project.json at every loop start, so nothing else
    needs touching. The caller (``pharos verify port``) makes sure the service is
    down first — a live service keeps its old port."""
    meta_path = L.project_dir(project) / "project.json"
    try:
        meta = json.loads(meta_path.read_text(encoding="utf-8"))
    except OSError:
        raise SystemExit(f"no such project: {project}")
    problem = verify_port_problem(port, project)
    if problem:
        raise SystemExit(problem)
    old = meta.get("verify_port")
    meta["verify_port"] = port
    atomic_write(meta_path, json.dumps(meta, ensure_ascii=False, indent=2))
    return {"project": project, "old_port": old, "verify_port": port}


def project_verify_port(project: str) -> Optional[int]:
    """The project's allocated verify port (from its project.json), if any."""
    meta = L.project_dir(project) / "project.json"
    try:
        port = json.loads(meta.read_text(encoding="utf-8")).get("verify_port")
    except (json.JSONDecodeError, OSError):
        return None
    return port if isinstance(port, int) else None


def _verify_url(project: Optional[str] = None) -> str:
    # Explicit URL, then project port, then the deployment's default port.
    env = os.environ.get("PHAROS_VERIFY_URL")
    if env:
        return env
    port = project_verify_port(project) if project else None
    if port is None:
        port = _verify_port_base()
    return f"http://127.0.0.1:{port}/verify"


def _verify_timeout() -> str:
    # MCP environment values must be TOML strings, even when their consumers
    # parse them as integers.
    return os.environ.get("PHAROS_VERIFY_TIMEOUT", "90000")


def _default_model() -> str:
    return os.environ.get("PHAROS_WORKER_MODEL") or codex.DEFAULT_MODEL


def write_codex_config(wl: "L.WorkerLayout") -> None:
    """Write worker MCP configuration using the current interpreter and project port."""
    atomic_write(wl.codex_config, _CODEX_CONFIG.format(
        python=_toml_str(sys.executable),
        project_dir=_toml_str(str(wl.project_dir)),
        author=_toml_str(wl.name),
        verify_url=_toml_str(_verify_url(wl.project)),
        verify_timeout=_toml_str(_verify_timeout()),
    ))


